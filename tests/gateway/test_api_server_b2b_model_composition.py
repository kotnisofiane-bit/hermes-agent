    def review(self, prepared, source, hermes_public):
        from backend.control_plane_g1.b2b_n4_provider import result_public_key, result_signer
        from dubsar_agent_context.native_transcript import render_native_context
        from scribe.model_authorization import ENDPOINT, ROUTE

        ready = self.ready
        mw = _review_read(ready, "get_mission_context")
        oc = _review_read(ready, "get_oc_context_view")
        assert mw["references"] == ready["mission_request"]["source_refs"]
        assert mw["source_digest"] == source["mission_source_digest"]
        for key in ("basis_digest", "authority_digest"):
            assert mw["mission_authority"][key] == source[{
                "basis_digest": "authority_basis_digest", "authority_digest": "authority_digest"}[key]]
        docs = mw["documents"]
