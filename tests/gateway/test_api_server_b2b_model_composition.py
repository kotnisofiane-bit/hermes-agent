def _sha(raw):
    return hashlib.sha256(raw).hexdigest()


def _write(path, value, mode=0o600):
    path.write_bytes(value if isinstance(value, bytes) else canonical_json(value))
    path.chmod(mode)
    return path


def _free_port():
    with socket.socket() as sock:
        sock.bind(("127.0.0.1", 0))
        value = sock.getsockname()[1]
        assert value >= 20000
        return value


def _raw_public(key):
    return key.public_bytes(Encoding.Raw, PublicFormat.Raw).hex()


def _run(cmd, *, cwd=None, env=None):
    return subprocess.run(cmd, cwd=cwd, env=env, capture_output=True, timeout=45, text=True)


def _result(process):
    assert process.returncode == 0, process.stderr
    return json.loads(process.stdout)


def _services(stack, temp, config):
    path = _write(temp / "services.json", config)
    log = stack.enter_context((temp / "services.log").open("w+"))
    child = subprocess.Popen(["node", str(FIXTURE), str(path)], stdout=subprocess.PIPE,
                             stderr=log, text=True)

    def stop():
        child.terminate()
        try:
            child.wait(10)
        except subprocess.TimeoutExpired:
            child.kill()
            child.wait(5)
        child.stdout.close()

    stack.callback(stop)
    with selectors.DefaultSelector() as poll:
        poll.register(child.stdout, selectors.EVENT_READ)
        assert poll.select(60), "native context services did not become ready"
    line = child.stdout.readline()
    if not line:
        log.seek(0)
        pytest.fail("native context services failed: " + log.read()[-3500:])
    ready = json.loads(line)
    assert ready["ready"] and ready["mode"] == config["mode"]
    if ready["native_source"]:
        assert ready["source_port"] >= 20000
    return ready


def _reader_result(path, tool, binding, rpc_id):
    """CI's actual peer/path/ownership/bounded-frame checks on every connection."""
    from asm_ipc import call_private

    message = {"contract": "dubsar.asm.mw-preflight-reader/1", "payload": {
        "jsonrpc": "2.0", "id": rpc_id, "method": "tools/call", "params": {
            "name": tool, "arguments": {"binding": binding}}}}
    answer = call_private(path, server_uid=os.geteuid(), request=message, timeout=3)
    assert answer["id"] == rpc_id and not answer["result"].get("isError"), answer
    return answer["result"]["content"][0]["text"]


def _review_read(ready, tool):
    """The reviewer uses its own authenticated socket read, never Hermes's view."""
    return json.loads(_reader_result(ready["socket_path"], tool, ready["reader_binding"], 1))


