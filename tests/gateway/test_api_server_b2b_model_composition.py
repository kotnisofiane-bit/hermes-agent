        self.request = ready["mission_request"]
        assert self.request["source_refs"] == [
            value for doc in ready["my_work"]["documents"]
            for value in (doc["native_ref"], doc["native_digest"])]
        self.frozen = missions.freeze_exact_revision(store_dir=str(self.store), mission_id=mission,
                                                     mission_request=self.request)
        self.provision_registration(stack)
        self.gateway_port = _free_port()
        self.core_port = _free_port()
        while self.core_port == self.gateway_port:
            self.core_port = _free_port()
        seed = self.key.private_bytes(Encoding.Raw, PrivateFormat.Raw, NoEncryption())
        _write(temp / "seed", base64.b64encode(seed))

